"""Output formats. Each reporter is a pure function `ScanResult -> str`."""

from __future__ import annotations

import json
from collections.abc import Callable
from itertools import groupby

from audit_agent import __version__
from audit_agent.models import Category, Finding, ScanResult, Severity

_CATEGORY_TITLES = {
    Category.SECURITY: "Security issues",
    Category.SLOP: "Slop (AI-style junk & dead code)",
    Category.GAP: "Coding gaps & loose ends",
}
_ICONS = {"critical": "🟥", "high": "🟧", "medium": "🟨", "low": "🟦", "info": "⬜"}


def _headline(result: ScanResult) -> str:
    counts = ", ".join(f"{n} {sev}" for sev, n in result.counts().items() if n)
    return f"{len(result.findings)} findings in {result.files_scanned} files ({counts or 'clean'})"


# --------------------------------------------------------------------------- text

def render_text(result: ScanResult) -> str:
    out = [f"audit-agent {__version__} - {result.root}", _headline(result), ""]
    if result.summary:
        out += ["== Summary (LLM triage) ==", result.summary.strip(), ""]
    by_cat = sorted(result.findings, key=lambda f: list(Category).index(f.category))
    for cat, group in groupby(by_cat, key=lambda f: f.category):
        items = list(group)
        out.append(f"== {_CATEGORY_TITLES[cat]} ({len(items)}) ==")
        for f in items:
            out.append(f"  [{f.severity.value.upper():8}] {f.rule_id} {f.location}")
            out.append(f"             {f.message}")
            if f.note:
                out.append(f"             note: {f.note}")
        out.append("")
    if result.dismissed:
        out.append(f"({len(result.dismissed)} findings dismissed as false positives by LLM triage)")
    return "\n".join(out).rstrip() + "\n"


# --------------------------------------------------------------------------- json

def render_json(result: ScanResult) -> str:
    payload = {
        "tool": {"name": "audit-agent", "version": __version__},
        "root": result.root,
        "files_scanned": result.files_scanned,
        "rules_run": result.rules_run,
        "counts": result.counts(),
        "by_category": result.by_category(),
        "llm_used": result.llm_used,
        "summary": result.summary,
        "findings": [f.to_dict() for f in result.findings],
        "dismissed": [f.to_dict() for f in result.dismissed],
    }
    return json.dumps(payload, indent=2, ensure_ascii=False) + "\n"


# --------------------------------------------------------------------------- markdown

def _md_escape(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render_markdown(result: ScanResult) -> str:
    out = ["# Code audit report", "", f"**{_headline(result)}**", ""]
    out += ["| Severity | Count |", "|---|---|"]
    out += [f"| {_ICONS[s]} {s} | {n} |" for s, n in result.counts().items()]
    out += ["", "| Category | Count |", "|---|---|"]
    out += [f"| {_CATEGORY_TITLES[Category(c)]} | {n} |" for c, n in result.by_category().items()]
    out.append("")
    if result.summary:
        out += ["## Prioritized summary", "", result.summary.strip(), ""]
    for cat in Category:
        items = [f for f in result.findings if f.category is cat]
        if not items:
            continue
        out += [f"## {_CATEGORY_TITLES[cat]} ({len(items)})", "", "| Sev | Rule | Location | Message |", "|---|---|---|---|"]
        for f in items:
            msg = _md_escape(f.message + (f" _(triage: {f.note})_" if f.note else ""))
            out.append(f"| {_ICONS[f.severity.value]} {f.severity.value} | `{f.rule_id}` | `{f.location}` | {msg} |")
        out.append("")
    if result.dismissed:
        out += [f"<details><summary>{len(result.dismissed)} dismissed as false positives</summary>", ""]
        out += [f"- `{f.rule_id}` `{f.location}`: {_md_escape(f.note)}" for f in result.dismissed]
        out += ["", "</details>", ""]
    out.append(f"_Generated by audit-agent {__version__}; {result.rules_run} rules; LLM triage: {'on' if result.llm_used else 'off'}._")
    return "\n".join(out) + "\n"


# --------------------------------------------------------------------------- sarif

_SARIF_LEVEL = {Severity.CRITICAL: "error", Severity.HIGH: "error", Severity.MEDIUM: "warning",
                Severity.LOW: "note", Severity.INFO: "note"}


def _sarif_result(f: Finding) -> dict:
    out: dict = {
        "ruleId": f.rule_id,
        "level": _SARIF_LEVEL[f.severity],
        "message": {"text": f.message + (f" (triage: {f.note})" if f.note else "")},
        "properties": {"severity": f.severity.value, "category": f.category.value},
    }
    if f.path != ".":  # repo-level findings (e.g. missing README) have no file to point at
        location: dict = {"physicalLocation": {"artifactLocation": {"uri": f.path}}}
        if f.line:
            location["physicalLocation"]["region"] = {"startLine": f.line}
        out["locations"] = [location]
    return out


def render_sarif(result: ScanResult) -> str:
    """SARIF 2.1.0, consumable by GitHub code scanning (upload-sarif action)."""
    rules: dict[str, dict] = {}
    for f in result.findings:
        rules.setdefault(f.rule_id, {
            "id": f.rule_id,
            "name": f.title,
            "shortDescription": {"text": f.title},
            "properties": {"category": f.category.value, "tags": [f.category.value]},
        })
    doc = {
        "$schema": "https://json.schemastore.org/sarif-2.1.0.json",
        "version": "2.1.0",
        "runs": [{
            "tool": {"driver": {"name": "audit-agent", "version": __version__, "rules": list(rules.values())}},
            "results": [_sarif_result(f) for f in result.findings],
        }],
    }
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


REPORTERS: dict[str, Callable[[ScanResult], str]] = {
    "text": render_text,
    "json": render_json,
    "markdown": render_markdown,
    "sarif": render_sarif,
}


def render(result: ScanResult, fmt: str) -> str:
    try:
        return REPORTERS[fmt](result)
    except KeyError:
        raise ValueError(f"unknown format {fmt!r}; choose from {', '.join(REPORTERS)}") from None
